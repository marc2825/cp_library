'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('../../visualizations/development_runtime/model.js');
const references=JSON.parse(fs.readFileSync(path.join(__dirname,'../development_runtime/visualization_expected.json'),'utf8'));
for(const {input,output} of references.debug)assert.equal(model.trace('debug',input).result.output,output);
for(const {input,result} of references.benchmark)assert.deepEqual(model.trace('benchmark',input).result,result);
const debug=model.modes.find(x=>x.id==='debug').sample;
assert.deepEqual(model.trace('debug',{...debug,enabled:false,value:null}).result,{enabled:false,output:'',evaluations:0});
assert.deepEqual(model.trace('debug',{...debug,onlineJudge:true,value:null}).result,{enabled:false,output:'',evaluations:0});
const interactive=model.modes.find(x=>x.id==='interactive').sample;
assert.deepEqual(model.trace('interactive',interactive).result,{status:'ok',bytes:25});
assert.equal(model.trace('interactive',{...interactive,events:[]}).result.status,'waiting');
assert.equal(model.trace('interactive',{...interactive,maxBytes:3}).result.status,'output_limit');
assert.equal(model.trace('interactive',{...interactive,events:[{time:3,from:'solver',stream:'exit',code:0}]}).result.status,'idle_timeout');
assert.equal(model.trace('interactive',{...interactive,timeout:1,events:[{time:2,from:'solver',stream:'exit',code:0}]}).result.status,'timeout');
assert.equal(model.trace('interactive',{...interactive,events:[{time:.1,from:'judge',stream:'exit',code:1}]}).result.status,'judge_exit');
for(const [mode,input] of [['debug',{...debug,maxItems:-1}],['debug',{...debug,value:{kind:'string',value:'日本語'}}],['interactive',{...interactive,timeout:0}],['benchmark',{goal:'maximize',seeds:[0,0],configurations:[]}]])assert.throws(()=>model.trace(mode,input));
for(const m of model.modes)assert.equal(model.trace(m.id,m.sample).steps.at(-1).title,'最終結果');
console.log('runtime model: 6 C++ formatting references, 40 Python summaries, 3 modes, errors and timeout/disabled boundaries passed');
